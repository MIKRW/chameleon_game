// === Trunk Interact 3 - Knotted ===
// Theme: narrow trunk with fine vertical bark grain
//
// No more dirt-dark 'D' knot/scar bands — those were full-width horizontal
// rows and read as stripes cutting across the trunk regardless of how the
// rest of the grain was drawn, so they're gone in favor of an all-vertical
// bark texture. Grain runs on three independent single-column 'h' highlight
// flecks: a primary column drifting a step left/right on a short/long
// cadence, a second column (further right in the fill) ticking on its own
// offset cadence, and a sparse third accent column between them on a much
// longer cadence for a bit of extra density — each on its own offset
// period, so they don't tick in the same rows and never line up into a
// horizontal band. Highlight-only (no dark shade in the fill) so the grain
// doesn't read as a stripe cutting through the trunk; the existing dark
// pillar-boundary columns (either side of the fill) carry the silhouette
// shading instead. Recolored off the dedicated walnut bark onto the shared
// r/R/h branch bark so this trunk's color matches the branches mounted on
// it. The 'kkkkkkkkkkk' base row marks the floor contact line for placement
// snapping.
// Size: 11x157 (grid units; multiply by render scale) — width bumped a
// third wider (8 -> 11, matching Trunk 1's gauge) and height matches the
// terrarium's full interior span (lid to floor), same as Trunk 1/2.
// Uses the shared TERRARIUM_PALETTE from palette/terrarium-palette.js.

